const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer, artisanAccount, retailerAccount] = await hre.ethers.getSigners();

  console.log("Deploying VeriCraft contract with Admin account:", deployer.address);

  const VeriCraft = await hre.ethers.getContractFactory("VeriCraft");
  const veriCraft = await VeriCraft.deploy();
  await veriCraft.waitForDeployment();

  const contractAddress = await veriCraft.getAddress();
  console.log("VeriCraft deployed to:", contractAddress);

  // 1. Register artisanAccount as a verified artisan
  console.log("Seeding verified artisan:", artisanAccount.address);
  const registerTx = await veriCraft
    .connect(deployer)
    .registerArtisan(
      artisanAccount.address,
      "Ramesh Kumar",
      "Channapatna Lacquerware",
      "Channapatna, Karnataka"
    );
  await registerTx.wait();
  console.log("Verified artisan registered: Ramesh Kumar");

  // 2. Mint Product #1 from artisanAccount
  const createTx = await veriCraft
    .connect(artisanAccount)
    .createProduct(
      "Handcrafted Rosewood Elephant",
      "Ivory Wood & Natural Vegetable Dyes",
      "ipfs://QmSampleHash001"
    );
  await createTx.wait();
  console.log("Minted Product #1: Handcrafted Rosewood Elephant");

  // 3. Transfer custody of Product #1 from artisanAccount to retailerAccount
  const transferTx = await veriCraft
    .connect(artisanAccount)
    .transferCustody(
      1,
      retailerAccount.address,
      "Artisan Cooperative Hub",
      "Artisan Cooperative Hub, Bengaluru",
      "Quality Verified & Dispatched"
    );
  await transferTx.wait();
  console.log("Transferred Product #1 custody to:", retailerAccount.address);

  // 4. Write deployed contract address and full ABI to frontend/contractConfig.js
  const artifact = await hre.artifacts.readArtifact("VeriCraft");
  const frontendDir = path.join(__dirname, "..", "frontend");
  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }

  const configPath = path.join(frontendDir, "contractConfig.js");
  const configFileContent = `// Auto-generated by scripts/deploy.js. Re-run deployment to update.
var CONTRACT_ADDRESS = ${JSON.stringify(contractAddress)};
var DEFAULT_RPC_URL = "http://127.0.0.1:8545";
var HARDHAT_DEMO_ACCOUNTS = ${JSON.stringify(
    [
      {
        label: "Admin (Deployer)",
        role: "Admin",
        address: deployer.address,
      },
      {
        label: "Ramesh Kumar (Artisan)",
        role: "Verified Artisan",
        address: artisanAccount.address,
      },
      {
        label: "Bengaluru Craft Hub (Handler)",
        role: "Handler",
        address: retailerAccount.address,
      },
    ],
    null,
    2
  )};
var CONTRACT_ABI = ${JSON.stringify(artifact.abi, null, 2)};
`;

  fs.writeFileSync(configPath, configFileContent, "utf8");
  console.log("Updated frontend/contractConfig.js successfully.");
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exitCode = 1;
});
